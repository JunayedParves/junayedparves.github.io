/* =====================================================================
   project-filter.js — filter buttons above a project grid
   ---------------------------------------------------------------------
   Markup (generated by scripts/build.js):
     <div class="filters" data-filter-for="GRID_ID"> <button data-filter="Power BI">…
     <ul id="GRID_ID"> <li class="project-card" data-tags="Power BI|Python">…
   A card shows when its data-tags contain the chosen filter ("All" = every card).
   ===================================================================== */
(function () {
  "use strict";

  document.querySelectorAll("[data-filter-for]").forEach(function (bar) {
    var grids = bar.getAttribute("data-filter-for").split(" ")
      .map(function (id) { return document.getElementById(id); })
      .filter(Boolean);
    var status = document.getElementById(bar.getAttribute("data-status"));

    bar.addEventListener("click", function (event) {
      var button = event.target.closest("[data-filter]");
      if (!button) return;
      var chosen = button.getAttribute("data-filter");

      bar.querySelectorAll("[data-filter]").forEach(function (b) {
        b.setAttribute("aria-pressed", String(b === button));
      });

      var shown = 0;
      grids.forEach(function (grid) {
        var count = 0;
        grid.querySelectorAll("[data-tags]").forEach(function (card) {
          var tags = card.getAttribute("data-tags").split("|");
          var match = chosen === "All" || tags.indexOf(chosen) !== -1;
          card.hidden = !match;
          if (match) count++;
        });
        shown += count;
        // hide a whole sub-gallery (and its heading) when nothing in it matches
        var block = grid.closest("[data-filter-block]");
        if (block) block.hidden = count === 0;
      });

      if (status) {
        status.textContent = shown
          ? "Showing " + shown + " " + (chosen === "All" ? "" : chosen + " ") + "project" + (shown === 1 ? "" : "s")
          : "No projects in this category yet.";
      }
    });
  });
})();
